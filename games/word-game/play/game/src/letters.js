// Checkpoints along each stroke (every ~0.1 of the box), in drawing order.
export function checkpoints(c) {
  const out = [];
  for (const path of STROKES[c] ?? []) {
    out.push({ x: path[0][0], y: path[0][1], s: 1 });
    for (let i = 1; i < path.length; i += 1) {
      const [x0, y0] = path[i - 1], [x1, y1] = path[i], d = Math.hypot(x1 - x0, y1 - y0), n = Math.max(1, Math.round(d / 0.11));
      for (let k = 1; k <= n; k += 1) out.push({ x: x0 + (x1 - x0) * k / n, y: y0 + (y1 - y0) * k / n, s: 0 });
    }
  }
  return out;
}

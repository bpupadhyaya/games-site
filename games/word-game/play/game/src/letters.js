export const TRACE_STYLES = [{ k: 'upper', label: 'Capital' }, { k: 'lower', label: 'Small' }, { k: 'cursive', label: 'Joined' }];
// Catmull-Rom smoothing so the joined letters flow (the guide points above are only the skeleton).
const smooth = (p) => {
  if (p.length < 3) return p;
  const out = [p[0]];
  for (let i = 0; i < p.length - 1; i += 1) {
    const a = p[Math.max(0, i - 1)], b = p[i], c = p[i + 1], d = p[Math.min(p.length - 1, i + 2)];
    for (let t = 1; t <= 4; t += 1) {
      const u = t / 4, u2 = u * u, u3 = u2 * u;
      out.push([0.5 * (2 * b[0] + (-a[0] + c[0]) * u + (2 * a[0] - 5 * b[0] + 4 * c[0] - d[0]) * u2 + (-a[0] + 3 * b[0] - 3 * c[0] + d[0]) * u3),
        0.5 * (2 * b[1] + (-a[1] + c[1]) * u + (2 * a[1] - 5 * b[1] + 4 * c[1] - d[1]) * u2 + (-a[1] + 3 * b[1] - 3 * c[1] + d[1]) * u3)]);
    }
  }
  return out;
};
const SMOOTH = {};
export const strokesFor = (c, style = 'upper') => {
  if (style === 'lower') return STROKES_LOWER[c] ?? [];
  if (style === 'cursive') return (SMOOTH[c] ??= (STROKES_CURSIVE[c] ?? []).map((p) => (p.length > 2 ? smooth(p) : p)));
  return STROKES[c] ?? [];
};
// Checkpoints along each stroke (every ~0.1 of the box), in drawing order. s:1 marks the start of a stroke (a stricter circle), n is the stroke number.
export function checkpoints(c, style = 'upper') {
  const out = []; let n = 0;
  for (const path of strokesFor(c, style)) {
    n += 1; out.push({ x: path[0][0], y: path[0][1], s: 1, n });
    for (let i = 1; i < path.length; i += 1) {
      const [x0, y0] = path[i - 1], [x1, y1] = path[i], d = Math.hypot(x1 - x0, y1 - y0), k = Math.max(1, Math.round(d / 0.11));
      for (let j = 1; j <= k; j += 1) out.push({ x: x0 + (x1 - x0) * j / k, y: y0 + (y1 - y0) * j / k, s: 0, n });
    }
  }
  return out;
}

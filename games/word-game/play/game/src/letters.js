// The alphabet: names (for the phone voice and the text fallback), look-alike groups, and simple stroke paths for tracing.
export const LETTERS = 'abcdefghijklmnopqrstuvwxyz'.split('');
export const LETTER_NAMES = { a: 'ay', b: 'bee', c: 'see', d: 'dee', e: 'ee', f: 'eff', g: 'gee', h: 'aitch', i: 'eye', j: 'jay', k: 'kay', l: 'el', m: 'em', n: 'en', o: 'oh', p: 'pee', q: 'cue', r: 'are', s: 'ess', t: 'tee', u: 'you', v: 'vee', w: 'double you', x: 'ex', y: 'why', z: 'zee' };
export const LOOKALIKES = ['bdpq', 'mnh', 'uvw', 'ij', 'ceo', 'gqy', 'fkt', 'ls', 'rn'];
export const VOWELS = new Set('aeiou');
export const letterEntry = (c) => ({ w: c, letter: true, up: c.toUpperCase(), name: LETTER_NAMES[c], band: -1, attrs: 0, syn: [], ant: [], gloss: '', pos: 'n', lex: 0, len: 1, rank: 0 });
export function similar(c, n, rng) {
  const g = LOOKALIKES.filter((s) => s.includes(c)).join('');
  const pool = [...new Set(g)].filter((x) => x !== c);
  const rest = LETTERS.filter((x) => x !== c && !pool.includes(x));
  return rng.shuffle(pool).concat(rng.shuffle(rest)).slice(0, n);
}
